export function factorial(n) {
  let f = 1;
  for (let i = 2; i <= n; i++) f *= i;
  return f;
}

// Probabilidad de espera de Erlang C. a = λ/μ (carga ofrecida), c servidores.
export function erlangC(a, c) {
  const rho = a / c;
  if (rho >= 1) return 1;
  let s = 0;
  for (let k = 0; k < c; k++) s += a ** k / factorial(k);
  const top = (a ** c / factorial(c)) * (1 / (1 - rho));
  return top / (s + top);
}
